//! Prints the validation report (markdown) comparing the sim against published KSP 1.12 numbers.
//! cargo run --release -p ksp-core --example validate > VALIDATION.md
use ksp_core::atmo::{self, KPA_TO_ATM};
use ksp_core::body::{self, KERBIN};
use ksp_core::engine;
use ksp_core::ksc;
use ksp_core::math::{v3, V3};
use ksp_core::sim::{self, Control, Params};
use ksp_core::vessel::{Craft, Placed, VesselSpec};

fn row(name: &str, sim: f64, refv: f64, unit: &str, src: &str) {
    let err = sim - refv;
    let rel = if refv != 0.0 { format!("{:.2e}", (err / refv).abs()) } else { "-".into() };
    println!("| {name} | {sim:.6} | {refv:.6} | {err:+.3e} {unit} | {rel} | {src} |");
}

fn engine_spec(def: ksp_core::parts::PartDef) -> ksp_core::vessel::EngineSpec {
    let c = Craft { parts: vec![Placed { def, pos: V3::ZERO, rot: ksp_core::math::Quat::IDENTITY, stack: vec![] }] };
    VesselSpec::compile(&c).engines[0]
}

fn main() {
    println!("# Validation report (generated by `cargo run --release -p ksp-core --example validate`)\n");
    println!("## 1. Kerbin, KSC and orbital constants vs published values\n");
    println!("| quantity | sim | published | error | rel | reference |\n|---|---|---|---|---|---|");
    row("Kerbin radius (m)", KERBIN.radius, 600_000.0, "m", "KSP wiki Kerbin");
    row("Kerbin GM (m^3/s^2)", KERBIN.gm(), 3.5316e12, "", "KSP wiki Kerbin (3.5316000e12)");
    row("Kerbin sidereal day (s)", KERBIN.sidereal_period(), 21_549.425, "s", "KSP wiki (5h 59m 9.425s)");
    row("Kerbin SOI (m)", KERBIN.sphere_of_influence(), 84_159_286.0, "m", "KSP wiki");
    row("Kerbin orbital period (s)", KERBIN.orbital_period(), 9_203_545.0, "s", "KSP wiki (426d 0h 32m 24.6s)");
    row("Equatorial surface speed (m/s)", KERBIN.angular_velocity() * KERBIN.radius, 174.94, "m/s", "KSP wiki (174.94 m/s)");
    row("Surface escape velocity (m/s)", (2.0 * KERBIN.gm() / KERBIN.radius).sqrt(), 3431.03, "m/s", "KSP wiki");
    row("Surface gravity (m/s^2)", KERBIN.gm() / KERBIN.radius.powi(2), 9.81, "m/s^2", "KSP wiki (9.81)");
    let mun = body::by_name("Mun").unwrap();
    row("Mun GM", mun.gm(), 6.5138398e10, "", "KSP wiki Mun");
    row("Mun SOI (m)", mun.sphere_of_influence(), 2_429_559.1, "m", "KSP wiki Mun");
    row("Atmosphere depth (m)", KERBIN.atmosphere_depth, 70_000.0, "m", "KSP wiki");
    let dlat = (-0.0972092543643722 - ksc::KSC_PAD_LAT_DEG).to_radians() * KERBIN.radius;
    let dlon = (-74.557706433623 - ksc::KSC_PAD_LON_DEG).to_radians() * KERBIN.radius;
    row("Pad latitude (deg)", ksc::KSC_PAD_LAT_DEG, -0.0972092543643722, "deg", "kOS community pad LATLNG");
    row("Pad longitude (deg)", ksc::KSC_PAD_LON_DEG, -74.557706433623, "deg", "kOS community pad LATLNG");
    println!("\nPad position offset vs the kOS value: {:.3} m N, {:.3} m E (|d| = {:.3} m).", dlat, dlon, dlat.hypot(dlon));
    println!("Pad deck vs the stock training saves' terrain raycast (alt - hgt): see `ksc::tests::matches_in_game_saves` (< 1 cm).\n");

    println!("## 2. Kerbin atmosphere (CelestialBody.GetPressure/GetTemperature/GetDensity, no sun offset)\n");
    println!("| alt (m) | P (kPa) | P (atm) | T (K) | rho (kg/m^3) | c (m/s) |\n|---|---|---|---|---|---|");
    for h in [0.0, 1000.0, 2500.0, 5000.0, 10000.0, 15000.0, 20000.0, 30000.0, 40000.0, 50000.0, 60000.0, 69000.0, 70000.0] {
        let p = atmo::pressure_kpa(KERBIN, h);
        let t = if p > 0.0 { atmo::temperature(KERBIN, h) } else { atmo::SPACE_TEMPERATURE };
        let r = atmo::density(KERBIN, p, t);
        println!("| {h:.0} | {p:.4} | {:.5} | {t:.2} | {r:.5} | {:.2} |", p * KPA_TO_ATM, atmo::speed_of_sound(KERBIN, p, r));
    }
    println!("\n| check | sim | published | error | rel | reference |\n|---|---|---|---|---|---|");
    let p0 = atmo::pressure_kpa(KERBIN, 0.0);
    let t0 = atmo::temperature(KERBIN, 0.0);
    let r0 = atmo::density(KERBIN, p0, t0);
    row("Sea-level pressure (kPa)", p0, 101.325, "kPa", "KSP wiki (1 atm)");
    row("Sea-level temperature curve (K)", t0, 288.15, "K", "KSP wiki / ISA");
    row("Sea-level density (kg/m^3)", r0, 1.225, "", "KSP wiki / ISA (1.225)");
    row("Sea-level speed of sound (m/s)", atmo::speed_of_sound(KERBIN, p0, r0), 340.29, "m/s", "ISA (KSP uses gamma 1.4, M 0.0289644)");
    // KSC-specific temperature offset over a day
    let up = ksc::KSC_PAD_DECK_BODY_FIXED.normalized();
    let (mut lo, mut hi) = (f64::INFINITY, f64::NEG_INFINITY);
    for k in 0..216 {
        let ut = k as f64 * 100.0;
        let (sun, ta) = sim::sun_dir_fixed(KERBIN, ut);
        let off = atmo::temperature_offset(KERBIN, sun, up, v3(0.0, 0.0, 1.0), ta, None);
        lo = lo.min(off);
        hi = hi.max(off);
    }
    println!("\nKSC sea-level temperature offset over one Kerbin day (GetAtmoThermalStats): {lo:.2} K .. {hi:.2} K");
    println!("-> sea-level density at KSC varies {:.4} .. {:.4} kg/m^3.\n",
        atmo::density(KERBIN, p0, atmo::full_temperature(KERBIN, 0.0, hi)), atmo::density(KERBIN, p0, atmo::full_temperature(KERBIN, 0.0, lo)));

    println!("## 3. Engines: thrust vs pressure (ModuleEngines), vs published part stats\n");
    println!("| check | sim | published | error | rel | reference |\n|---|---|---|---|---|---|");
    for (name, def, vac, asl) in [
        ("LV-T45 Swivel", ksp_core::parts::swivel(), 215.0, 167.969),
        ("LV-909 Terrier", ksp_core::parts::terrier(), 60.0, 14.783),
    ] {
        let e = engine_spec(def);
        let mut res = [1e9; 4];
        row(&format!("{name} vac thrust (kN)"), engine::burn(&e, 1.0, 0.0, &mut res, 0.02).0, vac, "kN", "KSP wiki / part info");
        row(&format!("{name} ASL thrust (kN)"), engine::burn(&e, 1.0, 1.0, &mut res, 0.02).0, asl, "kN", "KSP wiki / part info");
        row(&format!("{name} max fuel flow (t/s)"), e.max_fuel_flow, vac / (engine::isp(&e, 0.0) * 9.80665), "t/s", "maxThrust/(Isp0 g0)");
    }
    let e = engine_spec(ksp_core::parts::swivel());
    println!("\nSwivel Isp between keys (Unity AddKey smooth tangents): 0.25 atm {:.2} s, 0.5 atm {:.2} s, 0.75 atm {:.2} s (linear would be 302.5 / 285 / 267.5).\n",
        engine::isp(&e, 0.25), engine::isp(&e, 0.5), engine::isp(&e, 0.75));

    println!("## 4. Stock vessel dV / TWR (Tsiolkovsky with g0 = 9.80665, as KSP's DeltaV app)\n");
    println!("| craft | wet (t) | dry (t) | dV vac (m/s) | dV ASL (m/s) | TWR ASL |\n|---|---|---|---|---|---|");
    for (name, eng) in [("Mk1 pod + FL-T400 + LV-909", ksp_core::parts::terrier()), ("Mk1 pod + FL-T400 + LV-T45 (+3 LT-2) hopper", ksp_core::parts::swivel())] {
        let mut c = Craft { parts: vec![Placed { def: ksp_core::parts::mk1pod_v2(), pos: V3::ZERO, rot: ksp_core::math::Quat::IDENTITY, stack: vec![] }] };
        let t = c.stack_below(0, ksp_core::parts::fuel_tank_t400());
        let _ = c.stack_below(t, eng);
        if name.contains("hopper") {
            c = Craft::hopper();
        }
        let s = VesselSpec::compile(&c);
        let full = s.full_resources();
        let mut empty = full;
        empty[0] = 0.0;
        empty[1] = 0.0;
        let (wet, dry) = (s.mass_props(&full).0, s.mass_props(&empty).0);
        let e = &s.engines[0];
        let mut res = [1e9; 4];
        let tasl = engine::burn(e, 1.0, 1.0, &mut res, 0.02).0;
        println!("| {name} | {wet:.4} | {dry:.4} | {:.1} | {:.1} | {:.3} |", engine::isp(e, 0.0) * engine::ENGINE_G0 * (wet / dry).ln(),
            engine::isp(e, 1.0) * engine::ENGINE_G0 * (wet / dry).ln(), tasl / (wet * 9.81));
    }
    println!("\nCommunity/in-game value for Mk1 + FL-T400 + LV-909: ~2,750 m/s vacuum (KSP DeltaV readout uses the same formula).\n");

    println!("## 5. Aerodynamics: hopper drag, falling engine-first, engines off\n");
    println!("Effective CdA = drag / q, measured from a single sim tick at 100 m (drag = m (a - g - frame terms)).\n");
    println!("| speed (m/s) | mach | q (kPa) | drag (kN) | CdA (m^2) |\n|---|---|---|---|---|");
    let spec = VesselSpec::compile(&Craft::hopper());
    let prm = Params { ground: false, sun_temperature: false, ..Params::default() };
    let (e_, _n, u) = sim::pad_enu();
    let q = sim::attitude(u, e_);
    let cda = |v: f64| {
        let mut st = sim::state_at_pad(&spec, v3(0.0, 0.0, 100.0), v3(0.0, 0.0, -v), q, V3::ZERO, 0.0);
        let mut st0 = st;
        let p2 = Params { aero: false, ..prm };
        let info = sim::tick(&spec, &prm, &mut st, &Control::default());
        sim::tick(&spec, &p2, &mut st0, &Control::default());
        let drag = (st.v - st0.v).dot(u) / sim::FIXED_DT * info.mass;
        (info.atm.mach, info.atm.q_kpa, drag, drag / info.atm.q_kpa)
    };
    for v in [30.0, 100.0, 200.0, 280.0, 320.0, 360.0, 400.0, 500.0] {
        let (m, qk, d, c) = cda(v);
        println!("| {v:.0} | {m:.3} | {qk:.3} | {d:.3} | {c:.4} |");
    }
    // terminal velocity at 100 m: bisect drag(v) = m g
    let (m, _, _) = spec.mass_props(&spec.full_resources());
    let g = KERBIN.gm() / (KERBIN.radius + ksc::KSC_PAD_DECK_ALT + 100.0).powi(2);
    let (mut lo, mut hi) = (10.0, 1500.0);
    for _ in 0..60 {
        let mid = 0.5 * (lo + hi);
        if cda(mid).2 < m * g { lo = mid } else { hi = mid }
    }
    println!("\nTerminal velocity near sea level (full tanks, {m:.2} t, engine-first): {:.1} m/s (mach {:.2}).", lo, cda(lo).0);
    println!("No published in-game number exists for this exact craft; the per-face drag math is checked");
    println!("term-by-term against the decompiled DragCubeList/FlightIntegrator chain (aero.rs tests).");
    println!();
}
