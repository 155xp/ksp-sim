"""Generate crates/ksp-core/src/bodies_data.rs from ksp_data_local/bodies.json.

Every value is a serialized CelestialBody / OrbitDriver.orbit field of the stock Kerbol-system
prefab (KSP_Data/sharedassets9.assets, KSP 1.12.5 build 3190), written verbatim. Runtime-derived
quantities (gravParameter, SOI, sidereal period, ...) are NOT stored here; body.rs derives them
the way CelestialBody.Start / SetupConstants / CBUpdate do.

usage: python -I tools/gen_bodies_rs.py ksp_data_local/bodies.json crates/ksp-core/src/bodies_data.rs
"""
import json
import sys

ORDER = ["Sun", "Moho", "Eve", "Gilly", "Kerbin", "Mun", "Minmus", "Duna", "Ike", "Dres",
         "Jool", "Laythe", "Vall", "Tylo", "Bop", "Pol", "Eeloo"]
CURVES = ["atmospherePressureCurve", "atmosphereTemperatureCurve", "latitudeTemperatureBiasCurve",
          "latitudeTemperatureSunMultCurve", "axialTemperatureSunBiasCurve",
          "axialTemperatureSunMultCurve", "atmosphereTemperatureSunMultCurve",
          "eccentricityTemperatureBiasCurve"]


def f(x):
    r = repr(float(x))
    if r == "inf":
        return "f64::INFINITY"
    return r if ("." in r or "e" in r) else r + ".0"


def b(x):
    return "true" if x else "false"


def curve(c):
    ks = ", ".join(f"k({f(k['time'])}, {f(k['value'])}, {f(k['inSlope'])}, {f(k['outSlope'])})"
                   for k in c["keys"])
    assert all(k.get("weightedMode", 0) == 0 for k in c["keys"]), "weighted keys unsupported"
    assert c["preInfinity"] == 2 and c["postInfinity"] == 2, "only clamp wrap mode supported"
    return f"&[{ks}]"


def main(src, dst):
    bodies = json.load(open(src))["bodies"]
    idx = {n: i for i, n in enumerate(ORDER)}
    out = ["// @generated by tools/gen_bodies_rs.py from KSP_Data/sharedassets9.assets (KSP 1.12.5 b3190).",
           "// Serialized CelestialBody fields only; see body.rs for the runtime derivations.",
           "#![allow(clippy::excessive_precision, clippy::unreadable_literal)]",
           "use crate::body::RawBody;", "use crate::curve::{k, Key};", ""]
    for n in ORDER:
        d = bodies[n]
        od = d.get("orbitDriver")
        for c in CURVES:
            out.append(f"const {n.upper()}_{c.upper()}: &[Key] = {curve(d[c])};")
        o = od["orbit"] if od else {k: 0.0 for k in ["inclination", "eccentricity", "semiMajorAxis", "LAN",
                                                       "argumentOfPeriapsis", "meanAnomalyAtEpoch", "epoch"]}
        parent = f"Some({idx[od['referenceBody']]})" if od else "None"
        out += [f"pub const {n.upper()}: RawBody = RawBody {{",
                f"    name: {json.dumps(n)}, parent: {parent},",
                f"    gee_asl: {f(d['GeeASL'])}, radius: {f(d['Radius'])},",
                f"    rotates: {b(d['rotates'])}, rotation_period: {f(d['rotationPeriod'])}, solar_rotation_period: {b(d['solarRotationPeriod'])},",
                f"    initial_rotation_deg: {f(d['initialRotation'])}, tidally_locked: {b(d['tidallyLocked'])},",
                f"    inverse_rot_threshold_altitude: {f(d['inverseRotThresholdAltitude'])}, clamp_inverse_rot_threshold: {b(d['clampInverseRotThreshold'])},",
                f"    atmosphere: {b(d['atmosphere'])}, atmosphere_contains_oxygen: {b(d['atmosphereContainsOxygen'])}, atmosphere_depth: {f(d['atmosphereDepth'])},",
                f"    atm_temperature_sea_level: {f(d['atmosphereTemperatureSeaLevel'])}, atm_pressure_sea_level: {f(d['atmospherePressureSeaLevel'])},",
                f"    atm_molar_mass: {f(d['atmosphereMolarMass'])}, atm_adiabatic_index: {f(d['atmosphereAdiabaticIndex'])},",
                f"    atm_temperature_lapse_rate: {f(d['atmosphereTemperatureLapseRate'])}, atm_gas_mass_lapse_rate: {f(d['atmosphereGasMassLapseRate'])},",
                f"    atm_use_temperature_curve: {b(d['atmosphereUseTemperatureCurve'])}, atm_temperature_curve_is_normalized: {b(d['atmosphereTemperatureCurveIsNormalized'])},",
                f"    atm_use_pressure_curve: {b(d['atmosphereUsePressureCurve'])}, atm_pressure_curve_is_normalized: {b(d['atmospherePressureCurveIsNormalized'])},",
                f"    max_axial_dot: {f(d['maxAxialDot'])}, radius_atmo_factor: {f(d['radiusAtmoFactor'])},",
                f"    ocean: {b(d['ocean'])}, has_solid_surface: {b(d['hasSolidSurface'])}, is_star: {b(d['isStar'])},",
                f"    orbit_inclination_deg: {f(o['inclination'])}, orbit_eccentricity: {f(o['eccentricity'])}, orbit_sma: {f(o['semiMajorAxis'])},",
                f"    orbit_lan_deg: {f(o['LAN'])}, orbit_arg_pe_deg: {f(o['argumentOfPeriapsis'])}, orbit_mean_anomaly_at_epoch: {f(o['meanAnomalyAtEpoch'])}, orbit_epoch: {f(o['epoch'])},"]
        for c in CURVES:
            field = {"atmospherePressureCurve": "pressure_curve", "atmosphereTemperatureCurve": "temperature_curve",
                     "latitudeTemperatureBiasCurve": "latitude_temperature_bias_curve",
                     "latitudeTemperatureSunMultCurve": "latitude_temperature_sun_mult_curve",
                     "axialTemperatureSunBiasCurve": "axial_temperature_sun_bias_curve",
                     "axialTemperatureSunMultCurve": "axial_temperature_sun_mult_curve",
                     "atmosphereTemperatureSunMultCurve": "atmosphere_temperature_sun_mult_curve",
                     "eccentricityTemperatureBiasCurve": "eccentricity_temperature_bias_curve"}[c]
            out.append(f"    {field}: {n.upper()}_{c.upper()},")
        out += ["};", ""]
    out.append(f"pub const ALL: [RawBody; {len(ORDER)}] = [{', '.join(n.upper() for n in ORDER)}];")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
